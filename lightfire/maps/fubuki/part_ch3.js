/* fubuki / 第3章（ch=3）: ほこらの 氷が とざされ、村の人は 火を失っている */
(function () {
  'use strict';
  var h = PF.h;
  PF.maps.part('fubuki', 'ch3', {
    when: { lt: ['ch', 4] },
    dark: 0.12,
    objects: [
      h.npc('hunter', 'fur', 13, 4, 'l', async function (g, e, w) {
        if (g.flag('f.ice2')) await g.say('こおりが とけたのか! …その ひは、いったい。', w);
        else await g.say(['ほこらの みちが こおりついて いてな。', 'まきを もやしても すぐに かぜで きえちまう。', 'ひが あれば とけるんだが…。'], w);
      }, 'かりうど'),
      h.npc('kid', 'girl', 8, 12, 'r', ['ゆきだるま つくったの。でも さむくて てが かじかむ…。', 'ひなたぼっこ したいな。'], 'ユキ'),
      h.npc('woman', 'fur2', 15, 11, 'd', ['ひが きえてから、みんな いえに こもりっきりよ。', 'あなた、そのランプの ひは あたたかそうね…。'], 'むらびと'),
      h.npc('man', 'fur', 6, 11, 'r', ['このさとの ひは、ほこらの ひが もとだったと きく。', 'ほこらが こおれば、さとも こおる。'], 'むらびと')
    ],
    onEnter: async function (g) {
      if (g.flag('f.intro')) return;
      g.set('f.intro');
      await g.say(['ふぶきの さと。', 'ゆきと こおりに うもれた ちいさな むらだ。']);
    }
  });
  PF.maps.part('fubuki', 'ch4', {
    when: { gte: ['ch', 4] },
    objects: [
      h.npc('hunter', 'fur', 13, 4, 'l', ['ほこらの ひが もどって、むらに ひが ともった!', 'かぜも すこし おだやかに なった きがするぜ。'], 'かりうど'),
      h.npc('kid', 'girl', 8, 12, 'r', ['あったかい! ゆきだるまも すこし とけちゃった。', 'でも いいの! ひなたぼっこ できるもん!'], 'ユキ'),
      h.npc('woman', 'fur2', 15, 11, 'd', ['ともしびの ひを わけて もらったの。', 'ありがとう。ほんとうに ありがとう。'], 'むらびと'),
      h.npc('man', 'fur', 6, 11, 'r', ['ほこらの ひが かがやいてる。', 'ひがしの かざんにも おなじ ひが あるらしい。'], 'むらびと')
    ]
  });
})();
