  // ===== アトラス生成 =====
  var order = Object.keys(glyphs);
  var COLS = 32;
  var atlas = null, index = {};
  function buildAtlas() {
    var rowsN = Math.ceil(order.length / COLS);
    atlas = U.canvas(COLS * CELL_W, rowsN * CELL_H);
    var g = atlas.g;
    g.fillStyle = '#fff';
    order.forEach(function (ch, n) {
      var gl = glyphs[ch];
      var cx = (n % COLS) * CELL_W, cy = Math.floor(n / COLS) * CELL_H;
      index[ch] = { x: cx, y: cy };
      var ox = gl.ox || 0;
      gl.rows.forEach(function (bits, r) {
        bits.forEach(function (c) { g.fillRect(cx + c + ox, cy + 2 + r, 1, 1); });
      });
      if (gl.mark) gl.mark.forEach(function (p) { g.fillRect(cx + p[0], cy + 2 + p[1], 1, 1); });
    });
  }
  var tinted = {};
  function atlasFor(color) {
    if (!atlas) buildAtlas();
    var t = tinted[color];
    if (t) return t;
    t = U.canvas(atlas.width, atlas.height);
    t.g.drawImage(atlas, 0, 0);
    t.g.globalCompositeOperation = 'source-in';
    t.g.fillStyle = color;
    t.g.fillRect(0, 0, t.width, t.height);
    tinted[color] = t;
    return t;
  }

  F.COLORS = {
    w: null, y: '#f8e060', r: '#f86858', g: '#78e878', b: '#78b8f8', o: '#f8a040', p: '#f890d0', k: '#a0a0b8'
  };

  function expand(text) {
    text = String(text == null ? '' : text);
    if (text.indexOf('{N}') >= 0) {
      var n = (RR.State && RR.State.S && RR.State.S.name) || 'ソラ';
      text = text.split('{N}').join(n);
    }
    return text;
  }
  F.expand = expand;

  F.has = function (ch) { return !!glyphs[ch]; };
  F.adv = function (ch) {
    var gl = glyphs[ch];
    return gl ? gl.adv : CELL_W;
  };
  // 制御コードを除いた幅
  F.measure = function (text, scale) {
    text = expand(text);
    var w = 0, max = 0;
    for (var i = 0; i < text.length; i++) {
      var ch = text[i];
      if (ch === '{') { var e = text.indexOf('}', i); if (e > 0) { i = e; continue; } }
      if (ch === '\n') { max = Math.max(max, w); w = 0; continue; }
      w += F.adv(ch);
    }
    return Math.max(max, w) * (scale || 1);
  };

  // text を幅 maxW で折り返した行配列（スペースを優先して改行）
  F.wrap = function (text, maxW) {
    text = expand(text);
    var out = [];
    text.split('\n').forEach(function (para) {
      var line = '', lineW = 0, lastSpace = -1;
      for (var i = 0; i < para.length; i++) {
        var ch = para[i];
        if (ch === '{') {
          var e = para.indexOf('}', i);
          if (e > 0) { line += para.slice(i, e + 1); i = e; continue; }
        }
        var a = F.adv(ch);
        if (lineW + a > maxW && line.length) {
          if (lastSpace > 0) {
            out.push(line.slice(0, lastSpace));
            line = line.slice(lastSpace + 1);
            lineW = F.measure(line);
          } else {
            out.push(line);
            line = ''; lineW = 0;
          }
          lastSpace = -1;
          if (ch === ' ') continue;
        }
        if (ch === ' ') lastSpace = line.length;
        line += ch; lineW += a;
      }
      out.push(line);
    });
    return out;
  };

  // 描画。opt: {shadow, scale, align, count(表示文字数)}
  F.draw = function (g, text, x, y, color, opt) {
    opt = opt || {};
    text = expand(text);
    color = color || '#f8f8f8';
    var scale = opt.scale || 1;
    var shadow = opt.shadow === undefined ? '#101828' : opt.shadow;
    if (opt.align === 'center') x = Math.round(x - F.measure(text, scale) / 2);
    else if (opt.align === 'right') x = Math.round(x - F.measure(text, scale));
    x = Math.round(x); y = Math.round(y);
    if (shadow) drawRun(g, text, x + scale, y + scale, shadow, scale, opt.count, true);
    return drawRun(g, text, x, y, color, scale, opt.count, false);
  };
  function drawRun(g, text, x, y, color, scale, count, isShadow) {
    var cx = x, cy = y, col = color, shown = 0;
    var at = atlasFor(col);
    for (var i = 0; i < text.length; i++) {
      var ch = text[i];
      if (ch === '{') {
        var e = text.indexOf('}', i);
        if (e > 0) {
          var code = text.slice(i + 1, e);
          if (!isShadow && F.COLORS.hasOwnProperty(code)) {
            col = F.COLORS[code] || color;
            at = atlasFor(col);
          }
          i = e; continue;
        }
      }
      if (ch === '\n') { cx = x; cy += F.LINE * scale; continue; }
      if (count != null && shown >= count) break;
      shown++;
      var gl = glyphs[ch];
      if (!gl) { cx += CELL_W * scale; continue; }
      var p = index[ch] || (atlasFor(col), index[ch]);
      if (p && gl.rows.length) {
        g.drawImage(at, p.x, p.y, CELL_W, CELL_H, cx, cy, CELL_W * scale, CELL_H * scale);
      }
      cx += gl.adv * scale;
    }
    return cx;
  }

  // 16x16 漢字（クレジット用）
  var bigCache = {};
  F.drawBig = function (g, ch, x, y, color, scale) {
    scale = scale || 1;
    var key = ch + color;
    var c = bigCache[key];
    if (!c) {
      var pat = BIG[ch];
      if (!pat) return;
      c = U.canvas(16, 16);
      c.g.fillStyle = color;
      pat.forEach(function (row, r) {
        for (var i = 0; i < row.length; i++) if (row[i] === '#') c.g.fillRect(i, r, 1, 1);
      });
      bigCache[key] = c;
    }
    g.drawImage(c, Math.round(x), Math.round(y), 16 * scale, 16 * scale);
  };
  F.hasBig = function (ch) { return !!BIG[ch]; };

